#!/usr/bin/env node
/**
 * Brings the scenery of every world over from the design project.
 *
 *     node scripts/world-sets.mjs <level-thumb.js from the design project's export>
 *
 * The design project draws each world's picture (scripts/world-art.py) from a three.js
 * scene of its own, built by `build(L, name)` in `level-thumb.js`. That function is the
 * art: the game runs it to get the same props, ground, backdrop and lights, then moves
 * them out round each real hole (src/render/scenery/). This script lifts `build` out of
 * the file, leaves its body as it is, and makes the few changes the game needs:
 *
 * - it is exported, and takes a third argument, `hooks`;
 * - every demonstration course it lays reports itself (`hooks.course`), so the game
 *   knows where the design put its course and can leave that out, and so does the sign
 *   at its tee (`hooks.sign`), which the game numbers for each hole;
 * - the speckle and wood-grain textures it draws again for every prop are drawn once
 *   per set of arguments (`hooks.memo`): the same picture, a fraction of the memory;
 * - the room light it was lit by comes from the game (`L.env`), and three.js from an
 *   import of what it uses by name, so that the bundle keeps only those; `L.T` holds the
 *   few the game swaps for coarser versions on a phone.
 *
 * Every change is checked to apply exactly once: a design export that no longer
 * matches stops the script rather than produce a set that half works.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'render', 'scenery', 'design.js');

/** The demonstration pictures are 1440 by 900; their camera's shape is all that is kept of that. */
const HEADER = `export function build(L, name, hooks) {
    const W = 1440, H = 900;`;

const PATCHES = [
  ['  function build(L, name) {', HEADER],
  ['scene.environment = ENV;', 'scene.environment = L.env;'],
  ['      return { g, top: T0 };', '      hooks.course(o, g, T0);\n      return { g, top: T0 };'],
  [
    'const bump = (n = 9000, size = 2, rep) => ctex(256, 256, speckle(\'#808080\', n, 0.9, size), rep, false);',
    'const bump = hooks.memo(\'bump\', (n = 9000, size = 2, rep) => ctex(256, 256, speckle(\'#808080\', n, 0.9, size), rep, false));',
  ],
  ['const woodMap = (base, dark, rep, w = 512, h = 128) => ctex(w, h, (g) => {', 'const woodMap = hooks.memo(\'woodMap\', (base, dark, rep, w = 512, h = 128) => ctex(w, h, (g) => {'],
  ['\n    }, rep);\n    const std = ', '\n    }, rep));\n    const std = '],
  ['const felt = (col, rep = [3, 8]) => phys(\'#ffffff\', {', 'const felt = hooks.memo(\'felt\', (col, rep = [3, 8]) => phys(\'#ffffff\', {'],
  ['\n    });\n    const metal = ', '\n    }));\n    const metal = '],
  // The sign at the tee says "1": it reports itself, for the game to number it per hole.
  ["g.fillText('1', w / 2, h / 2 + 4); }) }), [0, 0.85, 0], [0, 0, 0], null, sg); }", "g.fillText('1', w / 2, h / 2 + 4); }) }), [0, 0.85, 0], [0, 0, 0], null, sg); hooks.sign(sg); }"],
];

function main() {
  const [source] = process.argv.slice(2);
  if (!source) {
    console.error('Usage: node scripts/world-sets.mjs <level-thumb.js>');
    process.exit(1);
  }
  const text = readFileSync(source, 'utf8');
  const start = text.indexOf('  function build(L, name) {');
  const endMarker = '    return Object.assign({ scene }, out);\n  }\n';
  const end = text.indexOf(endMarker, start);
  if (start < 0 || end < 0) throw new Error('No build(L, name) function found: is this the design project\'s level-thumb.js?');
  let body = text.slice(start, end + endMarker.length);
  for (const [from, to] of PATCHES) {
    const count = body.split(from).length - 1;
    if (count !== 1) throw new Error(`Expected one "${from.trim().slice(0, 60)}" in build(), found ${count}`);
    body = body.replace(from, to);
  }
  const used = [...new Set(body.match(/\bT\.[A-Za-z0-9_]+/g).map((name) => name.slice(2)))].sort();
  const three = 'const T = L.T, RB = L.RB;';
  if (body.split(three).length !== 2) throw new Error(`Expected one "${three}" in build()`);
  body = body.replace(three, `const T = { ${used.join(', ')}, ...L.T }, RB = L.RB;`);
  const banner = [
    '// Generated by scripts/world-sets.mjs from the design project\'s level-thumb.js.',
    '// Do not edit by hand: change the scene in the design project, export it, and run the',
    '// script again. It is the art of the game\'s scenery, kept as the design wrote it.',
    '',
  ].join('\n');
  const imports = `import { ${used.join(', ')} } from 'three';\n\n`;
  writeFileSync(OUT, `${banner}${imports}${body.replace(/^ {2}/gm, '')}`);
  console.log(`Scenery for ${new Set(body.match(/name === '[a-z0-9]+'/g)).size} scenes written to ${OUT}`);
}

main();
